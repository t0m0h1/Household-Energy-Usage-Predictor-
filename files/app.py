from datetime import datetime, time as dtime
from pathlib import Path

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

import data_utils
import features as ft
import model as ml

MODEL_PATH = Path(__file__).parent / "model.joblib"
PAGES = ["Overview", "Predict Usage", "Usage Trends", "Model Performance", "Dataset and Settings"]
TEAL, GREEN, GREY, AMBER = "#0f9d8a", "#2e9e5b", "#7a8a88", "#e08a1e"
WEEKDAYS = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
SYNTHETIC_LABEL = "Synthetic demonstration data"


# ----------------------------------------------------------------------------
# Small display helpers
# ----------------------------------------------------------------------------
def stretch():
    """Streamlit renamed use_container_width -> width="stretch" in newer versions."""
    version = tuple(int(part) for part in st.__version__.split(".")[:2] if part.isdigit())
    return {"width": "stretch"} if version >= (1, 50) else {"use_container_width": True}


def show_chart(fig, y_title=None):
    fig.update_layout(template="plotly_white", margin=dict(l=10, r=10, t=40, b=10),
                      hovermode="x unified", legend=dict(orientation="h", y=-0.2),
                      colorway=[TEAL, AMBER, GREY])
    if y_title:
        fig.update_yaxes(title=y_title)
    st.plotly_chart(fig, **stretch())


def show_table(df):
    st.dataframe(df, hide_index=True, **stretch())


def page_header(title, caption):
    st.title(title)
    st.caption(caption)
    if st.session_state["source"] == SYNTHETIC_LABEL:
        st.info("🧪 **Synthetic demonstration data** - generated by Python, not real household measurements.")


def inject_css():
    st.markdown("""<style>
    [data-testid="stMetric"] {background:#f2f8f6; border:1px solid #d3e9e3;
        border-radius:14px; padding:14px 16px;}
    .block-container {padding-top: 2rem; max-width: 1200px;}
    </style>""", unsafe_allow_html=True)


# ----------------------------------------------------------------------------
# Session state: dataset and model are kept so nothing retrains needlessly
# ----------------------------------------------------------------------------
def set_dataset(df, source, report):
    state = st.session_state
    state.update(df=df, source=source, report=report, bundle=None, bundle_error=None)
    state["dataset_id"] = state.get("dataset_id", 0) + 1


def use_synthetic_data():
    df = data_utils.generate_synthetic_data()
    report = {"messages": ["Generated by Python; nothing needed cleaning."],
              "missing_summary": df.isna().sum().rename("missing values in upload")
                                   .rename_axis("column").reset_index()}
    set_dataset(df, SYNTHETIC_LABEL, report)


def init_state():
    st.session_state.setdefault("uploader_version", 0)
    if "df" not in st.session_state:
        use_synthetic_data()


def get_bundle(force=False):
    """Return the trained model, training only when needed."""
    state = st.session_state
    if state.get("bundle") is not None and not force:
        return state["bundle"]
    try:
        with st.spinner("Training the Random Forest (first time only)..."):
            bundle, how = ml.get_or_train(state["df"], MODEL_PATH, force=force)
    except ValueError as err:
        state["bundle_error"] = str(err)
        return None
    state.update(bundle=bundle, bundle_error=None, bundle_how=how)
    return bundle


def need_model(bundle):
    """Show the reason there is no model; return True if the page should stop."""
    if bundle is None:
        st.error(st.session_state.get("bundle_error") or "The model could not be trained.")
        return True
    return False


def next_hour_prediction(df, bundle):
    """Estimate for the hour after the last reading (None if not possible)."""
    if bundle is None:
        return None
    timestamp = df["timestamp"].max() + pd.Timedelta(hours=1)
    temperature = float(df["temperature_c"].iloc[-1]) if bundle["use_temperature"] else None
    try:
        value, _ = ml.predict_for_timestamp(bundle, ft.to_hourly_series(df), timestamp, temperature)
    except ml.MissingHistoryError:
        return None
    return timestamp, value, temperature


def pick_date_range(df, key):
    low, high = df["timestamp"].min().date(), df["timestamp"].max().date()
    chosen = st.date_input("Date range", value=(low, high), min_value=low, max_value=high,
                           key=f"{key}-{st.session_state['dataset_id']}")
    if isinstance(chosen, (list, tuple)) and len(chosen) == 2:
        return chosen
    st.info("Select both a start date and an end date.")
    return None


# ----------------------------------------------------------------------------
# Page 1: Overview
# ----------------------------------------------------------------------------
def page_overview(df, bundle):
    page_header("Overview", "A summary of recorded electricity use (measured values) and the model's next estimate.")
    dates = pick_date_range(df, "overview-range")
    if dates is None:
        return
    start, end = dates
    day = df["timestamp"].dt.date
    view = df[(day >= start) & (day <= end)]
    if view.empty:
        st.warning("No readings in that date range.")
        return

    next_pred = next_hour_prediction(df, bundle)
    latest = df.iloc[-1]
    peak = view.loc[view["usage_kwh"].idxmax()]
    row1 = st.columns(3)
    row1[0].metric("Total consumption", f"{view['usage_kwh'].sum():,.0f} kWh", help="Sum of all readings in the selected range")
    row1[1].metric("Average per hour", f"{view['usage_kwh'].mean():.2f} kWh")
    row1[2].metric("Highest hourly reading", f"{peak['usage_kwh']:.2f} kWh", help=f"Recorded {peak['timestamp']:%d %b %Y, %H:%M}")
    row2 = st.columns(3)
    row2[0].metric("Most recent reading", f"{latest['usage_kwh']:.2f} kWh", help=f"Recorded {latest['timestamp']:%d %b %Y, %H:%M} (whole dataset)")
    if next_pred:
        stamp, value, temp = next_pred
        note = f"Predicted for {stamp:%d %b %Y, %H:%M}."
        if temp is not None:
            note += f" Assumes the temperature stays at the last recorded value ({temp:.1f} °C)."
        row2[1].metric("Next hour (predicted)", f"{value:.2f} kWh", help=note)
    else:
        row2[1].metric("Next hour (predicted)", "Not available", help="Needs a trained model and 24 recent hourly readings.")

    st.subheader("Electricity usage over time")
    mode = st.radio("Show", ["Hourly readings", "Daily average"], horizontal=True, key="overview-mode")
    series = view.set_index("timestamp")["usage_kwh"]
    if mode == "Daily average":
        series = series.resample("D").mean()
    fig = go.Figure(go.Scatter(x=series.index, y=series.values, mode="lines", name="Actual (measured)",
                               line=dict(color=TEAL, width=1.5), hovertemplate="%{y:.2f} kWh<extra>Actual</extra>"))
    if next_pred and mode == "Hourly readings" and end >= df["timestamp"].max().date():
        fig.add_trace(go.Scatter(x=[next_pred[0]], y=[next_pred[1]], mode="markers", name="Predicted (model)",
                                 marker=dict(color=AMBER, size=12, symbol="diamond"),
                                 hovertemplate="%{y:.2f} kWh<extra>Predicted</extra>"))
    show_chart(fig, "kWh")
    st.caption("Teal line = real measurements. The orange diamond (if shown) is the model's estimate, not a measurement.")

    st.subheader("Average usage by hour of day")
    by_hour = view.groupby(view["timestamp"].dt.hour)["usage_kwh"].mean().reset_index()
    fig = px.bar(by_hour, x="timestamp", y="usage_kwh", labels={"timestamp": "Hour of day", "usage_kwh": "Average kWh"})
    fig.update_traces(marker_color=TEAL, hovertemplate="Hour %{x}:00<br>%{y:.2f} kWh<extra></extra>")
    show_chart(fig)
    st.caption("Shows when electricity is typically used during the day, for the selected date range.")


