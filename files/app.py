# ----------------------------------------------------------------------------
def page_predict(df, bundle):
    page_header("Predict Usage", "Pick a date, time and conditions, then ask the trained model for an estimate.")
    if need_model(bundle):
        return
    dataset_id = st.session_state["dataset_id"]
    hourly = ft.to_hourly_series(df)
    default_stamp = df["timestamp"].max() + pd.Timedelta(hours=1)

    col1, col2 = st.columns(2)
    chosen_date = col1.date_input("Date", value=default_stamp.date(), key=f"pred-date-{dataset_id}")
    chosen_time = col2.time_input("Time (only the hour is used)", value=dtime(default_stamp.hour, 0),
                                  step=3600, key=f"pred-time-{dataset_id}")
    timestamp = pd.Timestamp(datetime.combine(chosen_date, dtime(chosen_time.hour, 0)))

    temperature = None
    if bundle["use_temperature"]:
        temperature = st.number_input("Outdoor temperature (°C)", -30.0, 50.0,
                                      float(round(df["temperature_c"].iloc[-1], 1)), 0.5,
                                      key=f"pred-temp-{dataset_id}",
                                      help="Pre-filled with the last recorded temperature. Change it for your scenario.")
    else:
        st.caption("This dataset has no temperature column, so the model does not use temperature.")

    st.markdown("**Recent electricity usage**")
    auto_lags, missing = ft.lags_from_history(hourly, timestamp)
    manual_lags = None
    if missing:
        st.warning(f"The dataset does not contain the 24 hourly readings before {timestamp:%d %b %Y %H:%M} "
                   f"({len(missing)} missing, from {missing[0]:%d %b %H:%M} to {missing[-1]:%d %b %H:%M}). "
                   "Please enter recent usage yourself below.")
        use_manual = True
    else:
        choice = st.radio("Where should recent usage come from?",
                          ["Use readings from the dataset", "Enter them manually"], horizontal=True,
                          key=f"pred-source-{dataset_id}")
        use_manual = choice == "Enter them manually"
        if not use_manual:
            with st.expander("Readings taken from the dataset"):
                show_table(pd.DataFrame({"Feature": [ft.LAG_DESCRIPTIONS[k] for k in ft.LAG_COLUMNS],
                                         "Value (kWh)": [round(float(auto_lags[k]), 3) for k in ft.LAG_COLUMNS]}))
    if use_manual:
        average = round(float(df["usage_kwh"].mean()), 2)
        st.caption(f"Boxes start at the dataset average ({average} kWh) as a convenience - replace them with your real readings.")
        cols = st.columns(5)
        values = [cols[i].number_input(label, 0.0, 50.0, average, 0.1, key=f"manual-{i}-{dataset_id}")
                  for i, label in enumerate(["1 h ago (kWh)", "2 h ago (kWh)", "3 h ago (kWh)",
                                             "24 h ago (kWh)", "24 h average (kWh)"])]
        manual_lags = ft.lags_from_manual(*values)

    if st.button("Predict Energy Usage", type="primary"):
        try:
            value, lags = ml.predict_for_timestamp(bundle, hourly, timestamp, temperature, manual_lags)
            st.session_state["prediction"] = dict(timestamp=timestamp, value=value, lags=lags,
                                                  temperature=temperature, dataset_id=dataset_id)
        except ValueError as err:
            st.error(str(err))
    result = st.session_state.get("prediction")
    if result and result["dataset_id"] == dataset_id:
        show_prediction(df, bundle, hourly, result)


def show_prediction(df, bundle, hourly, result):
    stamp, value, last_stamp = result["timestamp"], result["value"], df["timestamp"].max()
    overall = df["usage_kwh"].mean()
    typical = df.loc[df["timestamp"].dt.hour == stamp.hour, "usage_kwh"].mean()
    st.divider()
    st.subheader(f"Result for {stamp:%A %d %B %Y, %H:00}")
    cols = st.columns(3)
    cols[0].metric("Predicted consumption", f"{value:.2f} kWh")
    cols[1].metric("Average hour (all data)", f"{overall:.2f} kWh", delta=f"prediction is {(value / overall - 1) * 100:+.0f}%", delta_color="off")
    cols[2].metric(f"Typical at {stamp.hour:02d}:00", f"{typical:.2f} kWh", delta=f"prediction is {(value / typical - 1) * 100:+.0f}%", delta_color="off")

    window_end = min(stamp - pd.Timedelta(hours=1), last_stamp)
    history = hourly.loc[window_end - pd.Timedelta(hours=71): window_end].dropna()
    fig = go.Figure(go.Scatter(x=history.index, y=history.values, mode="lines", name="Actual (previous 72 h of data)",
                               line=dict(color=TEAL, width=2), hovertemplate="%{y:.2f} kWh<extra>Actual</extra>"))
    fig.add_trace(go.Scatter(x=[stamp], y=[value], mode="markers", name="Predicted",
                             marker=dict(color=AMBER, size=14, symbol="diamond"),
                             hovertemplate="%{y:.2f} kWh<extra>Predicted</extra>"))
    if stamp in hourly.index and pd.notna(hourly[stamp]):
        fig.add_trace(go.Scatter(x=[stamp], y=[hourly[stamp]], mode="markers", name="Actual at that time",
                                 marker=dict(color=GREY, size=12, symbol="circle-open", line=dict(width=2)),
                                 hovertemplate="%{y:.2f} kWh<extra>Actual</extra>"))
    show_chart(fig, "kWh")

    direction = "above" if value >= overall else "below"
    st.markdown(f"The model estimates **{value:.2f} kWh** for this hour, which is **{abs(value / overall - 1) * 100:.0f}% {direction}** "
                f"the average hour in the dataset and **{abs(value / typical - 1) * 100:.0f}% {'above' if value >= typical else 'below'}** "
                f"the typical {stamp.hour:02d}:00 reading. It combines the time of day, the day of the week and season, "
                f"{'the temperature, ' if bundle['use_temperature'] else ''}and recent usage "
                f"(last hour: {result['lags']['lag_1']:.2f} kWh, 24-hour average: {result['lags']['roll_mean_24']:.2f} kWh).")
    if stamp > last_stamp:
        st.warning("This is a **future estimate**. It may be less reliable if conditions differ from the data the model learned from.")
    if bundle["use_temperature"] and result["temperature"] is not None:
        low, high = df["temperature_c"].min(), df["temperature_c"].max()
        if not low <= result["temperature"] <= high:
            st.warning(f"{result['temperature']:.1f} °C is outside the temperatures in the data ({low:.1f} to {high:.1f} °C), so this estimate is an extrapolation.")
    if bundle["train_start"] <= stamp < bundle["test_start"]:
        st.info("This hour was part of the model's **training data**, so the model has already seen it. Do not treat this as a fair accuracy test.")


