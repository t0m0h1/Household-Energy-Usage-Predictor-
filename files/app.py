# Page 5: Dataset and Settings
# ----------------------------------------------------------------------------
def page_settings(df):
    state = st.session_state
    page_header("Dataset and Settings", "Upload your own hourly data, check how it was cleaned, and (re)train the model.")
    if state.get("flash"):
        st.success(state.pop("flash"))

    st.subheader("Upload a CSV")
    st.caption("Columns: `timestamp`, `usage_kwh` and optionally `temperature_c`. One reading per hour, at least 3 days.")
    upload = st.file_uploader("CSV file", type=["csv"], key=f"upload-{state['uploader_version']}")
    if upload is not None:
        signature = (upload.name, upload.size, state["uploader_version"])
        if state.get("upload_signature") != signature:
            try:
                clean, report = data_utils.load_csv(upload)
            except data_utils.DataValidationError as err:
                st.error(f"Could not use this file: {err}")
            else:
                state["upload_signature"] = signature
                set_dataset(clean, upload.name, report)
                state["flash"] = f"Loaded {upload.name}. The model will be trained when needed (or press the button below)."
                st.rerun()

    st.subheader("Current dataset")
    st.write(f"**Source:** {state['source']}")
    cols = st.columns(3)
    cols[0].metric("Records", f"{len(df):,}")
    cols[1].metric("From", f"{df['timestamp'].min():%d %b %Y}")
    cols[2].metric("To", f"{df['timestamp'].max():%d %b %Y}")
    st.markdown("**Preview (first 100 rows)**")
    show_table(df.head(100))

    left, right = st.columns(2)
    with left:
        st.markdown("**Missing values in the original upload**")
        show_table(state["report"]["missing_summary"])
    with right:
        st.markdown("**Data cleaning**")
        for message in state["report"]["messages"]:
            st.markdown(f"- {message}")

    st.subheader("Model")
    note = state.get("bundle_how")
    if state.get("bundle") is not None:
        st.write(f"A model is ready ({'loaded from disk' if note == 'loaded' else 'trained now'}). "
                 f"Inputs: {', '.join(state['bundle']['feature_columns'])}.")
    buttons = st.columns(3)
    if buttons[0].button("Train / retrain model", type="primary"):
        bundle = get_bundle(force=True)
        if bundle:
            st.success(f"Trained. Test MAE: {bundle['metrics']['random_forest']['mae']:.3f} kWh, R²: {bundle['metrics']['random_forest']['r2']:.3f}.")
        else:
            st.error(state["bundle_error"])
    if buttons[1].button("Reset to synthetic data"):
        use_synthetic_data()
        state["uploader_version"] += 1
        state["flash"] = "Reset to synthetic demonstration data."
        st.rerun()
    buttons[2].download_button("Download processed data", df.to_csv(index=False).encode("utf-8"),
                               file_name="processed_energy_data.csv", mime="text/csv")


# ----------------------------------------------------------------------------
# Main
# ----------------------------------------------------------------------------
def main():
    st.set_page_config(page_title="Household Energy Predictor", page_icon="⚡", layout="wide")
    inject_css()
    init_state()
    st.sidebar.title("⚡ Energy Predictor")
    page = st.sidebar.radio("Navigate", PAGES, label_visibility="collapsed")
    df = st.session_state["df"]
    st.sidebar.caption(f"Data: {st.session_state['source']} ({len(df):,} hourly rows)")

    if page == "Dataset and Settings":
        page_settings(df)
        return
    bundle = get_bundle()
    if page == "Overview":
        page_overview(df, bundle)
    elif page == "Predict Usage":
        page_predict(df, bundle)
    elif page == "Usage Trends":
        page_trends(df, bundle)
    else:
        page_performance(df, bundle)


main()
