def page_performance(df, bundle):
    page_header("Model Performance", "How well the Random Forest predicts hours it has never seen.")
    if need_model(bundle):
        return
    rf, base = bundle["metrics"]["random_forest"], bundle["metrics"]["baseline"]
    st.caption(f"Trained on the first {bundle['n_train']:,} hours ({bundle['train_start']:%d %b %Y} to {bundle['train_end']:%d %b %Y}); "
               f"tested on the final {bundle['n_test']:,} hours ({bundle['test_start']:%d %b %Y} to {bundle['test_end']:%d %b %Y}).")
    cols = st.columns(3)
    cols[0].metric("MAE", f"{rf['mae']:.3f} kWh", help="Average size of the prediction error. Lower is better.")
    cols[1].metric("RMSE", f"{rf['rmse']:.3f} kWh", help="Like MAE but punishes big mistakes more. Lower is better.")
    cols[2].metric("R²", f"{rf['r2']:.3f}", help="Share of the ups and downs in usage the model explains. 1 is perfect, 0 is no better than the average.")

    st.subheader("Comparison with a simple baseline")
    table = pd.DataFrame({"Metric": ["MAE (kWh)", "RMSE (kWh)", "R²"],
                          "Random Forest": [round(rf[k], 3) for k in ("mae", "rmse", "r2")],
                          "Baseline: always predict the training average": [round(base[k], 3) for k in ("mae", "rmse", "r2")]})
    show_table(table)
    if rf["mae"] < base["mae"]:
        st.success(f"On the test set, the Random Forest's average error is {(1 - rf['mae'] / base['mae']) * 100:.0f}% lower than the baseline's.")
    else:
        st.warning("On the test set the Random Forest did **not** beat the simple baseline, so its predictions should not be trusted for this data.")

    st.subheader("Actual versus predicted (test set)")
    pairs = pd.DataFrame({"Actual": bundle["test_actual"], "Predicted": bundle["test_predicted"]}).sample(
        min(bundle["n_test"], 3000), random_state=0)
    fig = px.scatter(pairs, x="Actual", y="Predicted", opacity=0.4, labels={"Actual": "Actual (kWh)", "Predicted": "Predicted (kWh)"})
    top = float(max(pairs.max()))
    fig.add_trace(go.Scatter(x=[0, top], y=[0, top], mode="lines", name="Perfect prediction", line=dict(color=GREY, dash="dash")))
    fig.update_traces(marker_color=TEAL, selector=dict(mode="markers"))
    fig.update_layout(hovermode="closest")
    show_chart(fig)
    st.caption("Dots on the dashed line are perfect predictions. The tighter the cloud around it, the better.")

    st.subheader("Feature importance")
    importance = bundle["importances"].reset_index()
    importance.columns = ["feature", "importance"]
    fig = px.bar(importance, x="importance", y="feature", orientation="h", labels={"importance": "Importance (share of total)", "feature": ""})
    fig.update_traces(marker_color=GREEN, hovertemplate="%{y}: %{x:.1%}<extra></extra>")
    show_chart(fig)
    st.caption("How much the forest relied on each input. Recent-usage features often dominate because usage changes gradually.")

    with st.expander("What do these metrics mean?"):
        st.markdown("- **MAE** - on average, predictions are off by this many kWh.\n"
                    "- **RMSE** - similar, but one big miss counts more than several small ones.\n"
                    "- **R²** - 1 means perfect, 0 means no better than guessing the average, negative means worse.\n"
                    "- **Baseline** - a deliberately naive model. A useful model must beat it.")


