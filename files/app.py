def page_trends(df, bundle):
    page_header("Usage Trends", "Interactive charts of how electricity use changes with time and temperature.")
    days = (df["timestamp"].max() - df["timestamp"].min()).days
    if len(df) < 48:
        st.info("At least 48 hourly readings are needed to show trends.")
        return

    st.subheader("1. Consumption over time")
    daily = df.set_index("timestamp")["usage_kwh"].resample("D").sum().reset_index()
    fig = px.line(daily, x="timestamp", y="usage_kwh", labels={"timestamp": "Date", "usage_kwh": "kWh per day"})
    fig.update_traces(line_color=TEAL, hovertemplate="%{y:.1f} kWh<extra>Daily total</extra>")
    show_chart(fig)
    st.caption("Total energy used each day. Look for seasonal changes and unusually high days.")

    st.subheader("2. Average consumption by hour")
    by_hour = df.groupby(df["timestamp"].dt.hour)["usage_kwh"].mean().reset_index()
    fig = px.bar(by_hour, x="timestamp", y="usage_kwh", labels={"timestamp": "Hour of day", "usage_kwh": "Average kWh"})
    fig.update_traces(marker_color=TEAL, hovertemplate="Hour %{x}:00<br>%{y:.2f} kWh<extra></extra>")
    show_chart(fig)
    st.caption("The daily routine: typically a morning and an evening peak.")

    st.subheader("3. Average consumption by weekday")
    if days < 7:
        st.info("At least 7 days of data are needed for a weekday comparison.")
    else:
        by_day = df.groupby(df["timestamp"].dt.dayofweek)["usage_kwh"].mean().reindex(range(7)).reset_index()
        by_day["day"] = WEEKDAYS
        fig = px.bar(by_day, x="day", y="usage_kwh", labels={"day": "Weekday", "usage_kwh": "Average kWh per hour"})
        fig.update_traces(marker_color=GREEN, hovertemplate="%{x}<br>%{y:.2f} kWh<extra></extra>")
        show_chart(fig)
        st.caption("Compares weekdays with weekends.")

    st.subheader("4. Consumption versus temperature")
    if "temperature_c" not in df.columns:
        st.info("This dataset has no temperature column, so this chart is unavailable.")
    else:
        sample = df.sample(min(len(df), 3000), random_state=0)
        fig = px.scatter(sample, x="temperature_c", y="usage_kwh", opacity=0.4,
                         labels={"temperature_c": "Temperature (°C)", "usage_kwh": "kWh per hour"})
        fig.update_traces(marker_color=TEAL, hovertemplate="%{x:.1f} °C<br>%{y:.2f} kWh<extra></extra>")
        fig.update_layout(hovermode="closest")
        show_chart(fig)
        st.caption("Each dot is one hour (a random sample of up to 3,000). A rise at low or high temperatures suggests heating or cooling.")

    st.subheader("5. Actual versus predicted")
    if bundle is None:
        st.info(st.session_state.get("bundle_error") or "No trained model is available.")
        return
    span = st.radio("Show", ["Last 7 days", "Last 30 days", "Whole test period"], horizontal=True, key="trend-span")
    actual, predicted = bundle["test_actual"], bundle["test_predicted"]
    hours = {"Last 7 days": 168, "Last 30 days": 720}.get(span, len(actual))
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=actual.index[-hours:], y=actual.values[-hours:], name="Actual", line=dict(color=TEAL, width=1.5)))
    fig.add_trace(go.Scatter(x=predicted.index[-hours:], y=predicted.values[-hours:], name="Predicted", line=dict(color=AMBER, width=1.5, dash="dot")))
    show_chart(fig, "kWh")
    st.caption("Only the held-out test period is shown: the model never saw these hours during training. Closer lines mean better predictions.")


